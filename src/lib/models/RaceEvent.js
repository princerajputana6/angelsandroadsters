import mongoose from 'mongoose';

/**
 * Append-only canonical race event (plan §8.1). One document per
 * user-confirmed action (start/lap/finish/DNF/penalty/correction/void).
 * History is NEVER overwritten — corrections and voids are new documents that
 * reference the original via `correctionOf` / `voidsEventId`.
 *
 * Idempotency is enforced by the unique `clientEventId` index AND the unique
 * `{deviceId, deviceSequence}` index. These are verified in the deployed
 * environment by the ensure-indexes script (plan §8.3) — the schema
 * declaration alone is not treated as a guarantee.
 */
export const RACE_EVENT_TYPES = [
  'RACE_STARTED',
  'RIDER_STARTED',
  'LAP_RECORDED',
  'RIDER_FINISHED',
  'DNF',
  'PENALTY',
  'CORRECTION',
  'VOID',
];

const raceEventSchema = new mongoose.Schema(
  {
    // Stable UUID generated by the source device at the moment of the action.
    // A retry of the SAME action reuses this id; it is the idempotency key.
    clientEventId: { type: String, required: true, unique: true, index: true },

    event: { type: mongoose.Schema.Types.ObjectId, ref: 'Event', required: true, index: true },
    race: { type: mongoose.Schema.Types.ObjectId, ref: 'Race', required: true, index: true },
    entry: { type: mongoose.Schema.Types.ObjectId, ref: 'RaceEntry', index: true },

    deviceId: { type: String, required: true, index: true },
    checkpointSessionId: { type: String, required: true, index: true },
    officialId: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },

    // Monotonic per-device counter allocated transactionally on the device.
    deviceSequence: { type: Number, required: true, min: 0 },

    type: { type: String, enum: RACE_EVENT_TYPES, required: true, index: true },

    // Client-reported occurrence time vs. server receipt time — kept separate.
    occurredAt: { type: Date, required: true },
    receivedAt: { type: Date, default: Date.now },

    // Timing diagnostics (plan §10.3). Monotonic values are only comparable
    // within the same device/session — never across devices.
    monotonicElapsedMs: { type: Number },
    clockOffsetMs: { type: Number },
    clockUncertaintyMs: { type: Number },

    // Strict, versioned payload (checkpointId, lapNumberCandidate, note, etc.)
    payload: { type: mongoose.Schema.Types.Mixed, default: {} },

    // Canonical hash of the identifying payload, used to distinguish a true
    // duplicate (same id, same content → ack) from an integrity conflict
    // (same id, different content → flag) (plan §9.1.7–9.1.8).
    payloadHash: { type: String, required: true },

    correctionOf: { type: mongoose.Schema.Types.ObjectId, ref: 'RaceEvent' },
    voidsEventId: { type: mongoose.Schema.Types.ObjectId, ref: 'RaceEvent' },

    schemaVersion: { type: Number, default: 1 },
  },
  { timestamps: true }
);

// Idempotency / ordering (verified by ensure-indexes script).
raceEventSchema.index({ deviceId: 1, deviceSequence: 1 }, { unique: true, name: 'uniq_device_sequence' });

// Dashboard / projection query indexes.
raceEventSchema.index({ race: 1, occurredAt: 1 });
raceEventSchema.index({ race: 1, entry: 1, occurredAt: 1 });

export default mongoose.models.RaceEvent || mongoose.model('RaceEvent', raceEventSchema);
